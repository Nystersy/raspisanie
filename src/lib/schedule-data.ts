// Преобразование даты dd.mm.yyyy → yyyy-mm-dd
function iso(d: string): string {
  const m = d.match(/(\d{2})\.(\d{2})\.(\d{4})/);
  if (!m) return d;
  return `${m[3]}-${m[2]}-${m[1]}`;
}

