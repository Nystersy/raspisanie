/** Возвращает ISO-дату (yyyy-mm-dd) без смещения часового пояса. */
function toISODate(d: Date): string {
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, "0");
  const day = String(d.getDate()).padStart(2, "0");
  return `${y}-${m}-${day}`;
}

/** Парсит ISO-дату в локальный Date. */
function fromISODate(s: string): Date {
  const [y, m, d] = s.split("-").map(Number);
  return new Date(y, m - 1, d);
}

/** Возвращает номер недели (1-based) для заданной даты. 0 = вне семестра. */
export function getWeekNumber(date: Date): number {
  const isoDate = toISODate(date);
  for (const w of WEEKS) {
    if (w.days[isoDate]) return w.week;
    // Если дата попадает в период недели, но нет практики (выходной)
  }
  // Проверка по периоду для дней без практики (воскресенья)
  for (const w of WEEKS) {
    const dates = Object.keys(w.days).sort();
    if (dates.length === 0) continue;
    const start = fromISODate(dates[0]);
    const end = fromISODate(dates[dates.length - 1]);
    const d = fromISODate(isoDate);
    if (d >= start && d <= end) return w.week;
  }
  return 0;
}

/** Возвращает дату первого учебного дня недели. */
export function getWeekStartDate(week: number): Date | null {
  const w = WEEKS.find((x) => x.week === week);
  if (!w) return null;
  const dates = Object.keys(w.days).sort();
  if (dates.length === 0) return null;
  return fromISODate(dates[0]);
}

/** Возвращает даты всех учебных дней недели (отсортированы). */
export function getWeekDates(week: number): Date[] {
  const w = WEEKS.find((x) => x.week === week);
  if (!w) return [];
  return Object.keys(w.days)
    .sort()
    .map((d) => fromISODate(d));
}

/** Индекс дня недели: 0=Пн ... 5=Сб, -1=Вс */
export function getDayIndex(date: Date): number {
  const jsDay = date.getDay();
  if (jsDay === 0) return -1;
  return jsDay - 1;
}

export interface DaySchedule {
  practice: SubjectKey | null;
  lectures: { time: string; subject: SubjectKey; room: string; slot: "lecture1" | "lecture2" }[];
  isWeekend: boolean;
  isHoliday: boolean;
  holidayNote?: string;
  weekNumber: number;
  note?: string;
}

/** Полное расписание на конкретный день. */
export function getDaySchedule(date: Date): DaySchedule {
  const isoDate = toISODate(date);
  const dayIdx = getDayIndex(date);

  // Праздничный день
  if (isoDate === SEMESTER.holidayDay) {
    return {
      practice: null,
      lectures: [],
      isWeekend: true,
      isHoliday: true,
      holidayNote: "Праздничный день — занятий нет",
      weekNumber: getWeekNumber(date),
    };
  }

  // Каникулярный перерыв
  if (isoDate >= SEMESTER.breakStart && isoDate <= SEMESTER.breakEnd) {
    return {
      practice: null,
      lectures: [],
      isWeekend: true,
      isHoliday: true,
      holidayNote: "Каникулярный перерыв",
      weekNumber: 0,
    };
  }

  // Зачётный день
  if (isoDate === SEMESTER.creditDay) {
    return {
      practice: null,
      lectures: [],
      isWeekend: false,
      isHoliday: true,
      holidayNote: "Зачётный день",
      weekNumber: 18,
    };
  }

  // Экзаменационная сессия
  if (isoDate >= SEMESTER.examSessionStart && isoDate <= SEMESTER.examSessionEnd) {
    return {
      practice: null,
      lectures: [],
      isWeekend: false,
      isHoliday: true,
      holidayNote: "Экзаменационная сессия",
      weekNumber: 0,
    };
  }

  // Каникулы после сессии
  if (isoDate >= SEMESTER.holidaysStart && isoDate <= SEMESTER.holidaysEnd) {
    return {
      practice: null,
      lectures: [],
      isWeekend: true,
      isHoliday: true,
      holidayNote: "Каникулы",
      weekNumber: 0,
    };
  }

  // Ищем неделю
  const week = WEEKS.find((w) => w.days[isoDate] !== undefined);
  const practice = week?.days[isoDate] ?? null;
  const lectures = LECTURES.filter((l) => l.date === isoDate).map((l) => ({
    time: l.time,
    subject: l.subject,
    room: l.room,
    slot: l.slot,
  }));

  const weekNumber = week?.week ?? 0;
  const isWeekend = dayIdx < 0 && !practice && lectures.length === 0;

  return {
    practice,
    lectures,
    isWeekend,
    isHoliday: false,
    weekNumber,
    note: week?.note,
  };
}

/** Расписание на всю неделю (все учебные дни недели). */
export function getWeekSchedule(week: number): { date: Date; schedule: DaySchedule }[] {
  const w = WEEKS.find((x) => x.week === week);
  if (!w) return [];
  return Object.keys(w.days)
    .sort()
    .map((d) => {
      const date = fromISODate(d);
      return { date, schedule: getDaySchedule(date) };
    });
}

