// ── Лекции по датам (из листа «Лекции по датам») ────────────────────
export interface LectureEntry {
  /** ISO дата */
  date: string;
  /** Время */
  time: string;
  subject: SubjectKey;
  /** Место проведения */
  room: string;
  slot: "lecture1" | "lecture2";
}

function L(date: string, time: string, subjectName: string, room: string): LectureEntry {
  return {
    date: iso(date),
    time,
    subject: sk(subjectName),
    room,
    slot: time.startsWith("14") ? "lecture1" : "lecture2",
  };
}

